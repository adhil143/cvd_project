@app.route("/api/fhir/Patient/<patient_id>")
@login_required
def get_fhir_patient(patient_id):
    # Log audit access
    log_audit("FHIR_EHR_FETCH_PATIENT", patient_id=patient_id)
    
    patient_data = MOCK_FHIR_PATIENTS.get(patient_id)
    if not patient_data:
        # Fallback: Query local SQLite database for a patient with this fhir_id
        local_patient = Patient.query.filter_by(fhir_id=patient_id).first()
        if local_patient:
            # Get latest visit metrics if available to pre-fill the form
            latest_visit = Visit.query.filter_by(patient_id=local_patient.id).order_by(Visit.visit_date.desc()).first()
            obs = {}
            if latest_visit:
                obs = {
                    "Sex_M": latest_visit.sex,
                    "ExerciseAngina_Y": latest_visit.exercise_angina,
                    "ST_Slope": latest_visit.st_slope,
                    "ChestPainType": latest_visit.chest_pain,
                    "Oldpeak": str(latest_visit.oldpeak)
                }
            patient_data = {
                "resourceType": "Patient",
                "id": local_patient.fhir_id,
                "name": [{"family": local_patient.name.split()[-1] if len(local_patient.name.split()) > 1 else "", 
                          "given": local_patient.name.split()[:-1] if len(local_patient.name.split()) > 1 else [local_patient.name]}],
                "gender": local_patient.gender.lower(),
                "birthDate": local_patient.dob,
                "clinicalObservations": obs
            }
        else:
            return jsonify({"error": "Patient not found in EHR or local database"}), 404
        
    return jsonify(patient_data)


@app.route("/api/shap/<int:visit_id>")
@login_required
def get_shap_json(visit_id):
    visit = db.session.get(Visit, visit_id)
    if not visit:
        return jsonify({"error": "Visit not found"}), 404
        
    visit_dict = {
        "Sex_M": visit.sex,
        "ExerciseAngina_Y": visit.exercise_angina,
        "ST_Slope": visit.st_slope,
        "ChestPainType": visit.chest_pain,
        "Oldpeak": str(visit.oldpeak)
    }
    X = encode_input(visit_dict)
    shap_values = explainer.shap_values(X)
    shap_row = shap_values[0]
    base_value = float(explainer.expected_value)
    
    groups = {
        "Sex": [],
        "Exercise-induced Angina": [],
        "ST Slope": [],
        "Chest Pain Type": [],
        "Oldpeak (ST Depression)": []
    }
    
    for i, feat in enumerate(top5_features):
        val = float(shap_row[i])
        if feat.startswith("Sex"):
            groups["Sex"].append(val)
        elif feat.startswith("ExerciseAngina"):
            groups["Exercise-induced Angina"].append(val)
        elif feat.startswith("ST_Slope"):
            groups["ST Slope"].append(val)
        elif feat.startswith("ChestPainType"):
            groups["Chest Pain Type"].append(val)
        elif feat.startswith("Oldpeak"):
            groups["Oldpeak (ST Depression)"].append(val)
        else:
            clean_name = feat.replace("_", " ")
            if clean_name not in groups:
                groups[clean_name] = []
            groups[clean_name].append(val)
            
    feature_list = []
    for group_name, vals in groups.items():
        if len(vals) > 0:
            feature_list.append({
                "name": group_name,
                "value": round(sum(vals), 4)
            })
            
    return jsonify({
        "base_value": base_value,
        "prediction_probability": visit.predicted_risk / 100.0,
        "features": feature_list
    })


