@app.route("/", methods=["GET", "POST"])
@login_required
def index():
    result = None
    selected_patient_id = request.args.get("patient_id") or request.form.get("patient_id")
    
    # Ignore URL patient_id if manually registering a new patient
    if request.method == "POST" and request.form.get("intake_method") == "manual":
        selected_patient_id = None
        
    selected_patient = None
    trajectory_chart = None
    previous_visits = []
    
    if selected_patient_id:
        selected_patient = db.session.get(Patient, selected_patient_id)
        if selected_patient:
            previous_visits = selected_patient.visits
            if len(previous_visits) >= 2:
                trajectory_chart = make_trajectory_chart(previous_visits)
            # Log view action
            log_audit("VIEW_PATIENT", patient_id=selected_patient.id)
                
    if request.method == "POST":
        X = encode_input(request.form)

        proba = model.predict_proba(X)[0, 1]
        risk_pct = round(float(proba) * 100, 1)

        # Get or create Patient
        fhir_id = request.form.get("patient_fhir_id")
        if fhir_id == "":
            fhir_id = None
            
        patient = None
        # Check if patient with this FHIR ID already exists to avoid duplication / constraint errors
        if fhir_id:
            patient = Patient.query.filter_by(fhir_id=fhir_id).first()
            
        if not patient and selected_patient_id:
            patient = db.session.get(Patient, selected_patient_id)
            # Update fhir_id if provided and different
            if fhir_id and patient.fhir_id != fhir_id:
                patient.fhir_id = fhir_id
                db.session.commit()
                
        if not patient:
            name = request.form.get("patient_name")
            dob = request.form.get("patient_dob")
            gender = request.form.get("patient_gender")
            if not name or not dob or not gender:
                name = name or "Unknown Patient"
                dob = dob or "1970-01-01"
                gender = gender or "Male"
            patient = Patient(name=name, dob=dob, gender=gender, fhir_id=fhir_id)
            db.session.add(patient)
            db.session.commit()
            # Log registration action
            log_audit("REGISTER_PATIENT", patient_id=patient.id)
            
        # Create and save Visit
        visit = Visit(
            patient_id=patient.id,
            sex=request.form.get("Sex_M", "0"),
            exercise_angina=request.form.get("ExerciseAngina_Y", "0"),
            st_slope=request.form.get("ST_Slope", "Up"),
            chest_pain=request.form.get("ChestPainType", "ATA"),
            oldpeak=float(request.form.get("Oldpeak", 0)),
            predicted_risk=risk_pct,
            is_high_risk=bool(risk_pct >= 50)
        )
        db.session.add(visit)
        db.session.commit()
        
        # Log prediction action
        log_audit("RUN_RISK_PREDICTION", patient_id=patient.id)
        
        # Redirect to the patient's view so they can see the updated trajectory!
        return redirect(url_for("index", patient_id=patient.id, last_visit_id=visit.id))

    # If redirection had last prediction results
    last_visit_id = request.args.get("last_visit_id")
    if last_visit_id:
        v = db.session.get(Visit, last_visit_id)
        if v:
            visit_dict = {
                "Sex_M": v.sex,
                "ExerciseAngina_Y": v.exercise_angina,
                "ST_Slope": v.st_slope,
                "ChestPainType": v.chest_pain,
                "Oldpeak": str(v.oldpeak)
            }
            X_last = encode_input(visit_dict)
            shap_values = explainer.shap_values(X_last)
            shap_row = shap_values[0]
            base_value = explainer.expected_value
            chart_b64 = make_shap_chart(X_last.iloc[0].values, shap_row, base_value)
            
            recs = get_clinical_recommendations(v.predicted_risk, visit_dict)
            
            result = {
                "risk_pct": v.predicted_risk,
                "chart": chart_b64,
                "recommendations": recs,
                "visit_id": v.id
            }

    patients = Patient.query.order_by(Patient.name).all()
    
    return render_template_string(
        PAGE_TEMPLATE, 
        fields=FORM_FIELDS, 
        result=result, 
        patients=patients,
        selected_patient=selected_patient,
        trajectory_chart=trajectory_chart,
        previous_visits=previous_visits
    )


