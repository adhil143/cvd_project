def get_clinical_recommendations(risk_pct, form_data):
    """Generate clinical guidance based on prediction score and patient indicators."""
    recs = []
    
    # General risk recommendations
    if risk_pct >= 60:
        recs.append("High probability of coronary artery disease. Urgent referral to a cardiologist for clinical evaluation is recommended.")
    elif risk_pct >= 30:
        recs.append("Intermediate risk. Recommend a non-invasive Cardiac Stress Test (stress ECG) or coronary CT angiography (CCTA) to evaluate ischemia.")
    else:
        recs.append("Low risk based on selected indicators. Continue primary prevention, blood pressure control, lipid management, and routine wellness checkups.")
        
    # Attribute-specific indicators
    st_slope = form_data.get("ST_Slope", "Up")
    exercise_angina = form_data.get("ExerciseAngina_Y", "0")
    oldpeak = float(form_data.get("Oldpeak", 0))
    chest_pain = form_data.get("ChestPainType", "ATA")
    
    if st_slope in ["Flat", "Down"]:
        recs.append("Abnormal ST-segment slope (Flat/Down) detected on exercise ECG, which is highly indicative of myocardial ischemia.")
        
    if exercise_angina == "1":
        recs.append("Patient experienced angina during physical exertion, suggesting inducible myocardial ischemia under stress.")
        
    if oldpeak > 1.0:
        recs.append(f"ST depression of {oldpeak} mm is clinically significant. Depressions > 1.0 mm suggest moderate-to-severe coronary stenosis.")
        
    if chest_pain == "TA":
        recs.append("Typical substernal chest pain provoked by exertion suggests classical angina. Further evaluation is strongly advised.")
        
    return recs


