# de-duplicate grouped fields (ST slope / chest pain each produce multiple
# one-hot columns but should show as ONE dropdown in the form)
def build_form_fields(features):
    seen_groups = set()
    fields = []
    for f in features:
        definition = FIELD_DEFINITIONS.get(f)
        if definition is None:
            fields.append({"key": f, "label": f, "type": "number"})
            continue
        group = definition["type"]
        if group in ("st_slope", "chest_pain"):
            if group in seen_groups:
                continue
            seen_groups.add(group)
        field_data = {"key": f, "label": definition["label"], "type": definition["type"]}
        if "options" in definition:
            field_data["options"] = definition["options"]
        fields.append(field_data)
    return fields


FORM_FIELDS = build_form_fields(top5_features)


def encode_input(form_data):
    """Turn form input into the exact 5-column vector the model expects,
    scaled using the same per-column mean/std the scaler learned."""
    raw = {feat: 0.0 for feat in top5_features}

    st_slope_choice = form_data.get("ST_Slope")   # "Up", "Flat", "Down"
    chest_pain_choice = form_data.get("ChestPainType")  # "ATA","NAP","TA","ASY"

    for feat in top5_features:
        if feat == "Sex_M":
            raw[feat] = float(form_data.get("Sex_M", 0))
        elif feat == "ExerciseAngina_Y":
            raw[feat] = float(form_data.get("ExerciseAngina_Y", 0))
        elif feat == "Oldpeak":
            raw[feat] = float(form_data.get("Oldpeak", 0))
        elif feat == "ST_Slope_Up":
            raw[feat] = 1.0 if st_slope_choice == "Up" else 0.0
        elif feat == "ST_Slope_Flat":
            raw[feat] = 1.0 if st_slope_choice == "Flat" else 0.0
        elif feat == "ChestPainType_ATA":
            raw[feat] = 1.0 if chest_pain_choice == "ATA" else 0.0
        elif feat == "ChestPainType_NAP":
            raw[feat] = 1.0 if chest_pain_choice == "NAP" else 0.0
        elif feat == "ChestPainType_TA":
            raw[feat] = 1.0 if chest_pain_choice == "TA" else 0.0

    # Scale each feature using its own mean/std from the fitted scaler
    scaled_values = []
    for feat in top5_features:
        idx = scaler_feature_order.index(feat)
        mean = scaler.mean_[idx]
        std = scaler.scale_[idx]
        scaled_values.append((raw[feat] - mean) / std)

    X = pd.DataFrame([scaled_values], columns=top5_features)
    return X


def make_shap_chart(X_row, shap_row, base_value):
    """Render a simple horizontal bar chart of SHAP contributions to a PNG (base64)."""
    # Group features by their form input representations (aligns 5 binary features to 4 form inputs)
    groups = {
        "Sex": [],
        "Exercise-induced Angina": [],
        "ST Slope": [],
        "Chest Pain Type": [],
        "Oldpeak (ST Depression)": []
    }
    
    for i, feat in enumerate(top5_features):
        val = shap_row[i]
        if feat.startswith("Sex"):
            groups["Sex"].append(val)
        elif feat.startswith("ExerciseAngina"):
            groups["Exercise-induced Angina"].append(val)
        elif feat.startswith("ST_Slope"):
            groups["ST Slope"].append(val)
        elif feat.startswith("ChestPainType"):
            groups["Chest Pain Type"].append(val)
        elif feat.startswith("Oldpeak"):
            groups["Oldpeak (ST Depression)"].append(val)
        else:
            clean_name = feat.replace("_", " ")
            if clean_name not in groups:
                groups[clean_name] = []
            groups[clean_name].append(val)
            
    # Sum the SHAP values in each group
    grouped_features = []
    grouped_shap = []
    for group_name, vals in groups.items():
        if len(vals) > 0:
            grouped_features.append(group_name)
            grouped_shap.append(sum(vals))
            
    grouped_features = np.array(grouped_features)
    grouped_shap = np.array(grouped_shap)
    
    # Create figure with clean transparent background
    fig, ax = plt.subplots(figsize=(6, 2.2), facecolor='none')
    ax.set_facecolor('none')
    
    # Custom dashboard colors (emerald for negative/reducing risk, crimson for positive/increasing risk)
    colors = ["#ef4444" if v > 0 else "#10b981" for v in grouped_shap]
    order = np.argsort(np.abs(grouped_shap))
    
    # Plot bars
    ax.barh(grouped_features[order], grouped_shap[order],
            color=np.array(colors)[order], height=0.55)
    
    # Add vertical line at zero
    ax.axvline(0, color='#cbd5e1', linestyle='-', linewidth=0.8)
    
    # Clean up axes & spines
    ax.spines['top'].set_visible(False)
    ax.spines['right'].set_visible(False)
    ax.spines['left'].set_color('#cbd5e1')
    ax.spines['bottom'].set_color('#cbd5e1')
    
    ax.tick_params(colors='#475569', labelsize=9)
    ax.xaxis.label.set_color('#475569')
    ax.xaxis.label.set_size(9)
    ax.set_xlabel("Contribution to Risk (SHAP Value)")
    
    plt.tight_layout()

    buf = io.BytesIO()
    # Save figure with transparent facecolor to blend with card
    plt.savefig(buf, format="png", dpi=120, bbox_inches='tight', transparent=True)
    plt.close(fig)
    buf.seek(0)
    return base64.b64encode(buf.read()).decode("utf-8")


def make_trajectory_chart(visits):
    """Render a line chart of risk progression over time."""
    if len(visits) < 2:
        return None
    # Create figure with clean transparent background
    fig, ax = plt.subplots(figsize=(6, 2.2), facecolor='none')
    ax.set_facecolor('none')
    
    # Sort visits by date
    sorted_visits = sorted(visits, key=lambda v: v.visit_date)
    dates = [v.visit_date.strftime("%m/%d %H:%M") for v in sorted_visits]
    risks = [v.predicted_risk for v in sorted_visits]
    
    ax.plot(dates, risks, marker='o', color='#4f46e5', linewidth=2, markersize=6)
